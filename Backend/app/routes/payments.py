@router.get("/history")
async def get_payment_history(current_user: dict = Depends(verify_token)):
    """Fetch user's transaction audit log."""
    db = get_db()
    user_id = current_user.get("sub")

    cursor = db["payments"].find({"user_id": user_id}).sort("created_at", -1)
    payments = await cursor.to_list(length=100)
    for p in payments:
        p["id"] = str(p["_id"])
        p.pop("_id", None)
        if isinstance(p.get("created_at"), datetime):
            p["created_at"] = p["created_at"].isoformat()
        if isinstance(p.get("updated_at"), datetime):
            p["updated_at"] = p["updated_at"].isoformat()
    return payments


@router.get("/{payment_id}")
async def get_payment_by_id(payment_id: str, current_user: dict = Depends(verify_token)):
    """Get single payment details by Razorpay Payment ID or ObjectId."""
    db = get_db()
    
    pay = await db["payments"].find_one({
        "$or": [{"payment_id": payment_id}, {"order_id": payment_id}]
    })

    if not pay:
        try:
            pay = await db["payments"].find_one({"_id": ObjectId(payment_id)})
        except Exception:
            pass

    if not pay:
        raise HTTPException(status_code=404, detail="Payment transaction not found")

    pay["id"] = str(pay["_id"])
    pay.pop("_id", None)
    return pay
