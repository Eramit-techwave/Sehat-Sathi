# 1. CREATE RAZORPAY ORDER
# ─────────────────────────────────────────────────────────────

@router.post("/create-order")
async def create_payment_order(
    req: CreateOrderRequest,
    current_user: dict = Depends(get_optional_user)
):
    """
    Creates an official Razorpay Order ID via Python SDK.
    Stores a pending transaction record in MongoDB payments collection.
    """
    db = get_db()
    user_id = current_user.get("sub")
    client = get_razorpay_client()

    amount_in_paise = int(round(req.amount * 100))

    try:
        # Call Razorpay Python SDK to create order
        razorpay_order = client.order.create({
            "amount": amount_in_paise,
            "currency": req.currency or "INR",
            "receipt": f"rcpt_{int(datetime.now().timestamp() * 1000)}",
            "notes": {
                "user_id": user_id,
                "booking_type": req.booking_type,
                **(req.notes or {})
            }
        })
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Razorpay Order Creation Failed: {str(e)}")

    order_id = razorpay_order["id"]

    # Store pending payment in MongoDB
    payment_doc = {
        "order_id": order_id,
        "payment_id": None,
        "user_id": user_id,
        "booking_type": req.booking_type,
        "amount": req.amount,
        "amount_paise": amount_in_paise,
        "currency": req.currency or "INR",
        "status": "created",
        "payment_method": None,
        "gateway": "razorpay",
        "notes": req.notes or {},
        "signature": None,
        "invoice_id": None,
        "created_at": datetime.now(),
        "updated_at": datetime.now()
    }

    await db["payments"].insert_one(payment_doc)

    return {
        "success": True,
        "order_id": order_id,
        "amount": razorpay_order["amount"],
        "currency": razorpay_order["currency"],
        "key_id": settings.RAZORPAY_KEY_ID
    }


