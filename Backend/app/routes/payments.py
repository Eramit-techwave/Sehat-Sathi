@router.post("/refund/{payment_id}")
async def initiate_refund(
    payment_id: str,
    req: RefundRequest,
    current_user: dict = Depends(verify_token)
):
    """
    Initiates full or partial refund via Razorpay Refund API.
    Updates payments, appointments, and invoices.
    Restricted to Doctor, Hospital, or Admin role.
    """
    db = get_db()
    user_id = current_user.get("sub")
    role = current_user.get("role")
    client = get_razorpay_client()

    payment_record = await db["payments"].find_one({"payment_id": payment_id})
    if not payment_record and role not in ["Admin", "Doctor", "Hospital"]:
        raise HTTPException(status_code=403, detail="Unauthorized to refund this payment")

    refund_data = {}
    if req.amount:
        refund_data["amount"] = int(round(req.amount * 100))

    try:
        refund_res = client.payment.refund(payment_id, refund_data)
        refund_id = refund_res.get("id")
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Razorpay Refund Error: {str(e)}")

    # Update payment status
    await db["payments"].update_one(
        {"payment_id": payment_id},
        {"$set": {
            "status": "refunded",
            "refund_id": refund_id,
            "refund_amount": req.amount or payment_record.get("amount"),
            "refund_reason": req.reason,
            "updated_at": datetime.now()
        }}
    )

    # Cancel associated appointment if any
    apt_id = payment_record.get("appointment_id") if payment_record else None
    if apt_id:
        try:
            await db["appointments"].update_one(
                {"_id": ObjectId(apt_id)},
                {"$set": {"status": "Cancelled", "payment_status": "Refunded", "cancelled_at": datetime.now()}}
            )
        except Exception:
            pass

    return {
        "success": True,
        "message": f"Refund initiated successfully! Refund ID: {refund_id}",
        "refund_id": refund_id,
        "payment_id": payment_id
    }


