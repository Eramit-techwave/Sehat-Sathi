@router.post("/verify")
async def verify_payment_and_confirm(
    req: VerifyPaymentRequest,
    current_user: dict = Depends(get_optional_user)
):
    """
    Backend ONLY Cryptographic Payment Verification.
    Verifies razorpay_order_id, razorpay_payment_id, and razorpay_signature using HMAC-SHA256.
    Commits the appointment/room/lab booking, generates GST invoice, and dispatches notifications.
    """
    db = get_db()
    user_id = current_user.get("sub")
    client = get_razorpay_client()

    # 1. Cryptographic HMAC-SHA256 Signature Verification
    try:
        client.utility.verify_payment_signature({
            'razorpay_order_id': req.razorpay_order_id,
            'razorpay_payment_id': req.razorpay_payment_id,
            'razorpay_signature': req.razorpay_signature
        })
    except Exception:
        # Signature mismatch or tampering
        raise HTTPException(
            status_code=400,
            detail="Payment verification failed: Invalid Razorpay cryptographic signature."
        )

    # 2. Fetch Payment details from Razorpay to get method (UPI, Card, NetBanking, etc.)
    payment_method_name = "UPI"
    try:
        rzp_payment = client.payment.fetch(req.razorpay_payment_id)
        raw_method = rzp_payment.get("method", "upi")
        payment_method_name = raw_method.upper()
    except Exception:
        pass

    # 3. Update payment document in MongoDB to 'captured'
    await db["payments"].update_one(
        {"order_id": req.razorpay_order_id},
        {"$set": {
            "payment_id": req.razorpay_payment_id,
            "signature": req.razorpay_signature,
            "status": "captured",
            "payment_method": payment_method_name,
            "updated_at": datetime.now()
        }},
        upsert=True
    )

    payload = req.booking_payload or {}
    booking_type = req.booking_type or "appointment"

    created_booking_id = None
    created_invoice_doc = None

    # 4. COMMIT BOOKING & GENERATE INVOICE BASED ON TYPE
    if booking_type == "appointment":
        # Check double booking
        doctor_id = payload.get("doctor_id")
        date_str = payload.get("date")
        slot_str = payload.get("time_slot")

        existing = await db["appointments"].find_one({
            "doctor_id": doctor_id,
            "date": date_str,
            "time_slot": slot_str,
            "status": {"$ne": "Cancelled"}
        })
        if existing:
            raise HTTPException(
                status_code=400,
                detail="This time slot was taken during checkout. Please choose another slot."
            )

        new_apt = {
            "patient_id": user_id,
            "doctor_id": doctor_id,
            "hospital_id": payload.get("hospital_id"),
            "date": date_str,
            "time_slot": slot_str,
            "status": "Confirmed",
            "reason": payload.get("reason") or "General Health Consultation",
            "payment_method": payment_method_name,
            "payment_status": "Paid",
            "amount": payload.get("amount") or 500.0,
            "transaction_id": req.razorpay_payment_id,
            "razorpay_order_id": req.razorpay_order_id,
            "created_at": datetime.now()
        }

        apt_res = await db["appointments"].insert_one(new_apt)
        created_booking_id = str(apt_res.inserted_id)

        # Generate GST Invoice
        inv_number = f"INV-2026-{random.randint(10000, 99999)}"
        base_amt = float(payload.get("amount") or 500.0)
        tax_amt = round(base_amt * 0.18, 2)
        total_amt = round(base_amt + tax_amt, 2)

        doctor_name = "Doctor Specialist"
        try:
            doc_user = await db["users"].find_one({"_id": ObjectId(doctor_id)})
            if doc_user:
                doctor_name = doc_user.get("name", "Doctor Specialist")
        except Exception:
            pass

        patient_name = current_user.get("name") or "Patient"

        created_invoice_doc = {
            "invoice_number": inv_number,
            "user_id": user_id,
            "patient_name": patient_name,
            "patient_id": f"PAT-{(user_id[:6]).upper()}",
            "doctor_name": doctor_name if doctor_name.startswith("Dr.") else f"Dr. {doctor_name}",
            "doctor_specialization": payload.get("doctor_specialty") or "General Physician",
            "hospital_name": payload.get("hospital_name") or "Sehat-Sathi Care Clinic",
            "service_name": "Doctor Consultation & Health Guidance",
            "base_amount": base_amt,
            "tax_rate": 18.0,
            "tax_amount": tax_amt,
            "discount": 0.0,
            "total_amount": total_amt,
            "payment_method": payment_method_name,
            "payment_status": "Paid",
            "reference_number": req.razorpay_payment_id,
            "transaction_id": req.razorpay_payment_id,
            "founder_name": "Amit Dubey",
            "company_name": "Sehat-Sathi",
            "company_url": "www.sehatsathi.com",
            "created_at": datetime.now()
        }

        inv_res = await db["invoices"].insert_one(created_invoice_doc)
        created_invoice_doc["id"] = str(inv_res.inserted_id)
        created_invoice_doc.pop("_id", None)

        # Update payment record with invoice ID
        await db["payments"].update_one(
            {"order_id": req.razorpay_order_id},
            {"$set": {"appointment_id": created_booking_id, "invoice_id": created_invoice_doc["id"]}}
        )

        # Dispatch Notifications
        await _notify(
            db, user_id, "appointment_booked",
            "Payment Confirmed & Appointment Booked 🎉",
            f"Your appointment with {doctor_name} on {date_str} at {slot_str} is confirmed (Paid via Razorpay).",
            {"appointment_id": created_booking_id, "payment_id": req.razorpay_payment_id}
        )

        if doctor_id and len(doctor_id) == 24:
            await _notify(
                db, doctor_id, "appointment_booked",
                "New Paid Appointment Booking 📅",
                f"{patient_name} booked an appointment for {date_str} at {slot_str} (Paid via Razorpay).",
                {"appointment_id": created_booking_id}
            )

    elif booking_type == "room":
        # Hospital Room Reservation
        hosp_id = payload.get("hospital_id")
        days = max(1, int(payload.get("duration_days") or 1))
        daily_rate = float(payload.get("daily_rate") or 1800.0)
        base_amt = round(daily_rate * days, 2)
