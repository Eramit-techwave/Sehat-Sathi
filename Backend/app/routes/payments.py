class CreateOrderRequest(BaseModel):
    amount: float = Field(..., gt=0, description="Amount in INR")
    currency: Optional[str] = Field("INR", description="Currency code (e.g. INR)")
    booking_type: str = Field(default="appointment", description="'appointment' | 'room' | 'lab'")
    notes: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Metadata notes for Razorpay Order")


class VerifyPaymentRequest(BaseModel):
    razorpay_order_id: str = Field(..., description="Order ID generated by Razorpay")
    razorpay_payment_id: str = Field(..., description="Payment ID generated by Razorpay Checkout")
    razorpay_signature: str = Field(..., description="Cryptographic HMAC-SHA256 signature from Razorpay")
    booking_type: Optional[str] = Field("appointment", description="'appointment' | 'room' | 'lab'")
    booking_payload: Dict[str, Any] = Field(..., description="Booking information to commit upon successful payment verification")


class RefundRequest(BaseModel):
    amount: Optional[float] = Field(None, description="Optional partial refund amount in INR. Omit for full refund.")
    reason: Optional[str] = Field("Patient Requested Refund / Cancellation", description="Reason for refund")


# ── Internal Notification Helper ──
async def _notify(db: Any, user_id: str, notif_type: str, title: str, message: str, metadata: Optional[Dict[str, Any]] = None) -> None:
    try:
        await db["notifications"].insert_one({
            "user_id": user_id,
            "type": notif_type,
            "title": title,
            "message": message,
            "is_read": False,
            "metadata": metadata or {},
            "created_at": datetime.now(),
        })
    except Exception:
        pass


