@router.post("/webhook")
async def razorpay_webhook(
    request: Request,
    x_razorpay_signature: Optional[str] = Header(None, alias="X-Razorpay-Signature")
):
    """
    Asynchronous Webhook Listener for Razorpay.
    Verifies X-Razorpay-Signature against RAZORPAY_WEBHOOK_SECRET.
    Handles payment.captured, payment.failed, order.paid, refund.processed.
    """
    db = get_db()
    client = get_razorpay_client()

    raw_body = await request.body()
    body_str = raw_body.decode("utf-8")

    # Verify signature if webhook secret is configured
    if settings.RAZORPAY_WEBHOOK_SECRET and x_razorpay_signature:
        try:
            client.utility.verify_webhook_signature(
                body_str,
                x_razorpay_signature,
                settings.RAZORPAY_WEBHOOK_SECRET
            )
        except Exception as sig_err:
            raise HTTPException(status_code=400, detail=f"Webhook Signature Verification Failed: {str(sig_err)}")

    import json
    try:
        event_data = json.loads(body_str)
    except Exception:
        return {"status": "ignored", "reason": "invalid_json"}

    event = event_data.get("event")
    payload = event_data.get("payload", {})

    print(f"[WEBHOOK] Received Razorpay event: {event}")

    if event == "payment.captured":
        payment_obj = payload.get("payment", {}).get("entity", {})
        order_id = payment_obj.get("order_id")
        payment_id = payment_obj.get("id")
        method = (payment_obj.get("method") or "upi").upper()

        if order_id:
            await db["payments"].update_one(
                {"order_id": order_id},
                {"$set": {
                    "payment_id": payment_id,
                    "status": "captured",
                    "payment_method": method,
                    "webhook_processed_at": datetime.now()
                }}
            )

    elif event == "payment.failed":
        payment_obj = payload.get("payment", {}).get("entity", {})
        order_id = payment_obj.get("order_id")
        error_desc = payment_obj.get("error_description", "Payment Failed")

        if order_id:
            await db["payments"].update_one(
                {"order_id": order_id},
                {"$set": {
                    "status": "failed",
                    "failure_reason": error_desc,
                    "webhook_processed_at": datetime.now()
                }}
            )

    elif event == "refund.processed":
        refund_obj = payload.get("refund", {}).get("entity", {})
        payment_id = refund_obj.get("payment_id")
        refund_id = refund_obj.get("id")

        if payment_id:
            await db["payments"].update_one(
                {"payment_id": payment_id},
                {"$set": {
                    "status": "refunded",
                    "refund_id": refund_id,
                    "webhook_processed_at": datetime.now()
                }}
            )

    return {"status": "ok", "event": event}


